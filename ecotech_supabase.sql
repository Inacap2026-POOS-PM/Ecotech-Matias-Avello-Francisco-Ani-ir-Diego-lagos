BEGIN;

CREATE SCHEMA IF NOT EXISTS ecotech;

REVOKE ALL ON SCHEMA ecotech
FROM PUBLIC, anon, authenticated;


-- Empleados

CREATE TABLE IF NOT EXISTS ecotech.empleado (
    id_empleado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    correo VARCHAR(150) NOT NULL,
    fecha_inicio DATE NOT NULL,
    salario NUMERIC(12, 2) NOT NULL,
    rol VARCHAR(50) NOT NULL DEFAULT 'Empleado',

    CONSTRAINT ck_empleado_salario
        CHECK (salario >= 0),

    CONSTRAINT ck_empleado_nombre
        CHECK (CHAR_LENGTH(TRIM(nombre)) > 0)
);

-- Se aplica también a las instalaciones que ya tienen la tabla empleado.
ALTER TABLE ecotech.empleado
    DROP CONSTRAINT IF EXISTS ck_empleado_rol,
    ADD CONSTRAINT ck_empleado_rol
        CHECK (rol IN ('Empleado', 'Gerente', 'Administrador'));

ALTER TABLE ecotech.empleado
    ADD COLUMN IF NOT EXISTS invitacion_hash TEXT,
    ADD COLUMN IF NOT EXISTS invitacion_vence TIMESTAMPTZ;

CREATE UNIQUE INDEX IF NOT EXISTS idx_empleado_invitacion
    ON ecotech.empleado (invitacion_hash)
    WHERE invitacion_hash IS NOT NULL;

ALTER TABLE ecotech.empleado
    ADD COLUMN IF NOT EXISTS rut VARCHAR(10);

CREATE UNIQUE INDEX IF NOT EXISTS idx_empleado_rut
    ON ecotech.empleado (rut)
    WHERE rut IS NOT NULL;


-- Cuentas de usuario

CREATE TABLE IF NOT EXISTS ecotech.cuenta_usuario (
    id_cuenta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL UNIQUE,
    nombre_usuario VARCHAR(50) COLLATE "C" NOT NULL UNIQUE,
    correo VARCHAR(150) NOT NULL,
    contrasena_cifrada BYTEA NOT NULL,

    CONSTRAINT ck_cuenta_cifrado
        CHECK (OCTET_LENGTH(contrasena_cifrada) <= 2048),

    CONSTRAINT fk_cuenta_empleado
        FOREIGN KEY (id_empleado)
        REFERENCES ecotech.empleado (id_empleado)
        ON DELETE CASCADE
);


-- Historial de cambios

CREATE TABLE IF NOT EXISTS ecotech.historial_cambios (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    operacion VARCHAR(20) NOT NULL
        CHECK (operacion IN ('AGREGAR', 'ACTUALIZAR', 'ELIMINAR')),

    entidad VARCHAR(30) NOT NULL
        CHECK (
            entidad IN (
                'EMPLEADO',
                'CUENTA_USUARIO',
                'PROYECTO',
                'DEPARTAMENTO',
                'ASIGNACION'
            )
        ),

    id_registro INTEGER,
    id_empleado INTEGER,

    -- El código del proyecto usa este nombre para guardar CURRENT_USER.
    usuario_mysql VARCHAR(288) NOT NULL,

    detalle VARCHAR(500) NOT NULL,
    datos_anteriores TEXT,
    datos_nuevos TEXT
);


-- Proyectos

CREATE TABLE IF NOT EXISTS ecotech.proyecto (
    id_proyecto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion_proyecto VARCHAR(255) NOT NULL,
    fecha_de_inicio DATE NOT NULL,
    miembro VARCHAR(100) NOT NULL,
    presupuesto NUMERIC(12, 2) NOT NULL,

    CONSTRAINT ck_proyecto_presupuesto
        CHECK (presupuesto >= 0),

    CONSTRAINT ck_proyecto_nombre
        CHECK (CHAR_LENGTH(TRIM(nombre)) > 0)
);


-- Departamentos

CREATE TABLE IF NOT EXISTS ecotech.departamento (
    id_departamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    departamento VARCHAR(100) NOT NULL,
    gerente_id INTEGER NOT NULL,

    CONSTRAINT fk_departamento_gerente
        FOREIGN KEY (gerente_id)
        REFERENCES ecotech.empleado (id_empleado)
        ON DELETE RESTRICT,

    CONSTRAINT ck_departamento_nombre
        CHECK (CHAR_LENGTH(TRIM(nombre)) > 0)
);


-- Asignaciones

CREATE TABLE IF NOT EXISTS ecotech.asignacion (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    horas_trabajadas INTEGER NOT NULL,
    tareas_realizadas VARCHAR(255) NOT NULL,
    id_empleado INTEGER,
    id_proyecto INTEGER,

    CONSTRAINT ck_asignacion_horas
        CHECK (horas_trabajadas >= 0),

    CONSTRAINT fk_asignacion_empleado
        FOREIGN KEY (id_empleado)
        REFERENCES ecotech.empleado (id_empleado)
        ON DELETE RESTRICT,

    CONSTRAINT fk_asignacion_proyecto
        FOREIGN KEY (id_proyecto)
        REFERENCES ecotech.proyecto (id_proyecto)
        ON DELETE RESTRICT
);


-- Índices para las consultas del sistema

CREATE INDEX IF NOT EXISTS idx_departamento_gerente
    ON ecotech.departamento (gerente_id);

CREATE INDEX IF NOT EXISTS idx_asignacion_empleado
    ON ecotech.asignacion (id_empleado);

CREATE INDEX IF NOT EXISTS idx_asignacion_proyecto
    ON ecotech.asignacion (id_proyecto);

CREATE INDEX IF NOT EXISTS idx_historial_empleado_fecha
    ON ecotech.historial_cambios (id_empleado, fecha);

CREATE INDEX IF NOT EXISTS idx_historial_fecha
    ON ecotech.historial_cambios (fecha);

CREATE INDEX IF NOT EXISTS idx_historial_entidad_id_fecha
    ON ecotech.historial_cambios (entidad, id_registro, fecha);


-- Seguridad de las tablas

ALTER TABLE ecotech.empleado ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.cuenta_usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.historial_cambios ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.proyecto ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.departamento ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.asignacion ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA ecotech
FROM PUBLIC, anon, authenticated;

REVOKE ALL ON ALL SEQUENCES IN SCHEMA ecotech
FROM PUBLIC, anon, authenticated;

DO $$
BEGIN
    IF to_regprocedure('public.rls_auto_enable()') IS NOT NULL THEN
        REVOKE EXECUTE ON FUNCTION public.rls_auto_enable()
        FROM PUBLIC, anon, authenticated;
    END IF;
END $$;

REVOKE CREATE ON SCHEMA ecotech
FROM PUBLIC, anon, authenticated;

ALTER DEFAULT PRIVILEGES IN SCHEMA ecotech
    REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;

ALTER DEFAULT PRIVILEGES IN SCHEMA ecotech
    REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;


-- Registro por invitación.
-- El administrador ingresa nombre, RUT, fecha de contrato y salario.
-- El empleado completa dirección, teléfono y correo al activar su cuenta.

ALTER TABLE ecotech.empleado
    ALTER COLUMN direccion DROP NOT NULL,
    ALTER COLUMN telefono DROP NOT NULL,
    ALTER COLUMN correo DROP NOT NULL,
    DROP CONSTRAINT IF EXISTS ck_empleado_contacto_invitacion,
    ADD CONSTRAINT ck_empleado_contacto_invitacion CHECK (
        (
            direccion IS NOT NULL
            AND telefono IS NOT NULL
            AND correo IS NOT NULL
        )
        OR (
            rol = 'Empleado'
            AND direccion IS NULL
            AND telefono IS NULL
            AND correo IS NULL
            AND invitacion_hash IS NOT NULL
            AND invitacion_vence IS NOT NULL
        )
    );

COMMIT;


-- Comprobación final

SELECT
    tablename AS tabla,
    rowsecurity AS seguridad_activa
FROM pg_tables
WHERE schemaname = 'ecotech'
ORDER BY tablename;